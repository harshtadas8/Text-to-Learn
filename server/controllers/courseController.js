/* =====================================================
   GET /api/courses/:id/full
===================================================== */
export async function getFullCourseController(req, res) {
  try {
    const { id } = req.params;

    const course = await Course.findById(id).lean();
    if (!course) {
      return res.status(404).json({
        success: false,
        message: "Course not found",
      });
    }

    // 🔥 Fetch cached lessons
    const lessons = await Lesson.find({ courseId: id }).lean();

    const lessonMap = {};
    lessons.forEach((lesson) => {
      const key = `${lesson.moduleIndex}-${lesson.lessonIndex}`;
      lessonMap[key] = lesson.content;
    });

    course.content.modules.forEach((module) => {
      module.lessons = module.lessons.map((lesson) => {
        const key = `${module.moduleIndex}-${lesson.lessonIndex}`;
        return {
          ...lesson,
          fullContent: lessonMap[key] || null,
        };
      });
    });

    return res.json({
      success: true,
      data: course,
    });

  } catch (error) {
    logger.error("❌ Full course fetch error:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to fetch full course",
    });
  }
}

/* =====================================================
   DELETE /api/courses/:id
===================================================== */
export async function deleteCourseController(req, res) {
  try {
    const { id } = req.params;
    const userId = req.auth.sub;

    const course = await Course.findById(id);

    if (!course) {
      return res.status(404).json({
        success: false,
        message: "Course not found",
      });
    }

    // Check if the user is the owner of the course
    if (course.userId !== userId) {
      return res.status(403).json({
        success: false,
        message: "You are not authorized to delete this course",
      });
    }

    await Course.findByIdAndDelete(id);
    
    // Delete associated lessons
    await Lesson.deleteMany({ courseId: id });

    // Invalidate Redis caches
    await clearUserCache(userId);
    await clearPublicCache();

    return res.json({
      success: true,
      message: "Course deleted successfully",
    });
  } catch (error) {
    logger.error("❌ Course deletion error:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to delete course",
    });
  }
}
