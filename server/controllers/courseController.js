/* =====================================================
   POST /api/courses/extract-text
===================================================== */
export async function extractTextController(req, res) {
  try {
    if (!req.file) {
      return res.status(400).json({ error: 'No file uploaded' });
    }

    let text = '';
    const mimeType = req.file.mimetype;

    if (mimeType === 'application/pdf') {
      const data = await pdfParse(req.file.buffer);
      text = data.text;
    } else if (mimeType === 'text/plain') {
      text = req.file.buffer.toString('utf-8');
    } else {
      return res.status(400).json({ error: 'Unsupported file type. Only PDF and TXT are allowed.' });
    }

    if (text.length > 50000) {
      text = text.substring(0, 50000) + '... [TRUNCATED]';
    }

    res.json({ text });
  } catch (error) {
    logger.error('Error extracting text:', error);
    res.status(500).json({ error: 'Failed to extract text from file' });
  }
}

