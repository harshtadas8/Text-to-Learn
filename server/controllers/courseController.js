import { logger } from "../config/logger.js";
import Course from "../models/Course.js";
import Lesson from "../models/Lesson.js";
import User from "../models/User.js";
import { generateCourseWithGemini } from "../services/ai/gemini.service.js";
import { clearUserCache, clearPublicCache } from "../utils/cacheInvalidator.js";

/* =====================================================
   POST /api/courses/generate
===================================================== */
export async function generateCourseController(req, res) {
  try {
    const { topic, level, language = "English", goal, timeAvailable, sourceMaterial = "" } = req.body;

    // 🔐 Auth0 user id
    const userId = req.auth.sub;
    
    // Fetch user memory
    const user = await User.findOne({ auth0Id: userId });

    const content = await generateCourseWithGemini(topic, level, language, goal, timeAvailable, user, sourceMaterial);

    const course = await Course.create({
      topic,
      level,
      language,
      goal,
      timeAvailable,
      content,
      userId, // ✅ saved
    });

    // Invalidate Redis caches
    await clearUserCache(userId);
    await clearPublicCache();

    res.status(201).json({ success: true, data: course });
  } catch (e) {
    logger.error(e);
    res.status(500).json({ success: false, message: "Course generation failed" });
  }
}

